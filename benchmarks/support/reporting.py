"""Benchmark summaries, portable result files and revision comparisons."""
import csv
import hashlib
import importlib.metadata
import json
import platform
import subprocess
import sys
from pathlib import Path

from rich.console import Console
from rich.table import Table

CONSOLE = Console()


def make_report(args, scenes, root, timestamp):
    """Record enough context to distinguish repository changes from workload changes."""
    def git(*arguments):
        try:
            return subprocess.check_output(["git", *arguments], cwd=root, text=True,
                                           stderr=subprocess.DEVNULL, timeout=5).strip()
        except (OSError, subprocess.SubprocessError):
            return None

    digest = hashlib.sha256()
    for scene in scenes:
        digest.update(scene["name"].encode())
        digest.update(Path(scene["file"]).read_bytes())
    for name in ["algorithms.py", "assets.py", "hilbert_visuals.py"]:
        digest.update((Path(__file__).parent / name).read_bytes())
    helpers = b"".join((Path(__file__).parent / name).read_bytes()
                       for name in ["algorithms.py", "assets.py", "hilbert_visuals.py"])
    scene_hashes = {scene["name"]: hashlib.sha256(Path(scene["file"]).read_bytes() + helpers).hexdigest()
                    for scene in scenes}
    versions = {}
    for name in ["manimgl", "wgpu", "numpy", "av", "psutil"]:
        try:
            versions[name] = importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            versions[name] = None
    config_hash = hashlib.sha256()
    for path in [root / "manimlib/default_config.yml", root / "custom_config.yml"]:
        if path.exists():
            config_hash.update(path.read_bytes())
    return {
        "schema_version": 6, "created_at_utc": timestamp,
        "resolution": args.resolution, "fps": args.fps, "phases": ["first", "cached"],
        "encoding": {"codec": "libx264rgb", "pixel_format": "rgb24", "crf": 0},
        "scenes": scenes, "workload_sha256": digest.hexdigest(),
        "scene_sha256": scene_hashes,
        "repository": {"commit": git("rev-parse", "HEAD"), "status": git("status", "--porcelain")},
        "environment": {"platform": platform.platform(), "python": sys.version, "packages": versions},
        "config_sha256": config_hash.hexdigest(), "runs": [], "interrupted": False,
    }


def comparison_rows(baseline, candidate):
    if baseline.get("schema_version") != 6 or candidate.get("schema_version") != 6:
        raise ValueError("Use results.json files generated by the current runner")
    for key in ["resolution", "fps", "encoding", "phases"]:
        if baseline.get(key) != candidate.get(key):
            raise ValueError(f"Cannot compare: {key} differs; use the same scenes, settings and benchmark sources")
    if baseline.get("interrupted") or candidate.get("interrupted"):
        raise ValueError("Cannot compare interrupted runs; finish both suites first")
    baseline_names = {scene["name"] for scene in baseline["scenes"]}
    candidate_names = {scene["name"] for scene in candidate["scenes"]}
    if not candidate_names <= baseline_names:
        raise ValueError("Baseline lacks some selected scenes")
    if baseline.get("workload_sha256") != candidate.get("workload_sha256"):
        subset_matches = candidate_names < baseline_names and all(
            candidate.get("scene_sha256", {}).get(name) is not None and
            candidate["scene_sha256"][name] == baseline.get("scene_sha256", {}).get(name)
            for name in candidate_names)
        if not subset_matches:
            raise ValueError("Cannot compare: workload_sha256 differs; use unchanged benchmark sources")
    for report in (baseline, candidate):
        expected = {(scene["name"], phase) for scene in report["scenes"] for phase in ("first", "cached")}
        if {(row["name"], row["phase"]) for row in report["summary"]} != expected:
            raise ValueError("Cannot compare incomplete suites; some selected scenes have no results")
    old = {(row["name"], row["phase"]): row for row in baseline["summary"]}
    rows = []
    for current in candidate["summary"]:
        previous = old.get((current["name"], current["phase"]))
        if previous is None:
            raise ValueError(f"Baseline has no result for {current['name']}")
        complete = (previous["status"] == current["status"] == "ok"
                    and previous.get("visual_passed") is not False
                    and current.get("visual_passed") is not False)
        def change(field):
            before, after = previous[field], current[field]
            return 100 * (after / before - 1) if complete and before and after is not None else None

        rows.append({"name": current["name"], "phase": current["phase"], "baseline_seconds": previous["render_seconds"],
                     "candidate_seconds": current["render_seconds"],
                     "render_change_percent": change("render_seconds"),
                     "wall_change_percent": change("wall_seconds")})
    return rows


def compare(baseline_path, candidate_path):
    def read(path):
        path = path / "results.json" if path.is_dir() else path
        return json.loads(path.read_text())

    baseline, candidate = read(baseline_path), read(candidate_path)
    rows = comparison_rows(baseline, candidate)
    for key in ["environment", "config_sha256"]:
        if baseline.get(key) != candidate.get(key):
            CONSOLE.print(f"[yellow]Review {key}: it differs between these runs.[/yellow]")
    old_adapters = {json.dumps(run.get("adapter"), sort_keys=True) for run in baseline["runs"]}
    new_adapters = {json.dumps(run.get("adapter"), sort_keys=True) for run in candidate["runs"]}
    if old_adapters != new_adapters:
        CONSOLE.print("[yellow]GPU adapter identity differs between these runs.[/yellow]")
    table = Table(title="Candidate vs baseline · separate run timings", padding=(0, 0))
    for title in ["Scene", "Phase", "Baseline s", "Candidate s", "Render Δ%", "Wall Δ%"]:
        table.add_column(title, justify="left" if title == "Scene" else "right")
    for row in rows:
        cells = [f"{row[key]:.2f}" if row[key] is not None else "—" for key in
                 ["baseline_seconds", "candidate_seconds", "render_change_percent", "wall_change_percent"]]
        table.add_row(row["name"], row["phase"], *cells)
    CONSOLE.print(table)
    CONSOLE.print("Negative = faster; positive = slower. Failed renders or visual checks have no percentage.")


def summarize(runs):
    fields = ["wall_seconds", "render_seconds", "render_fps", "cpu_percent",
              "tree_peak_mib", "worker_peak_mib", "device_gpu_utilization_percent"]
    return [{"name": run["name"], "phase": run["phase"], "status": run["status"],
             "visual_passed": run.get("visual", {}).get("passed"),
             **{field: run.get(field) if run["status"] == "ok" else None for field in fields}}
            for run in runs]


def save_report(report, output):
    report["video_generation_seconds"] = sum(run["wall_seconds"] for run in report["runs"])
    report["summary"] = summarize(report["runs"])
    (output / "results.json").write_text(json.dumps(report, indent=2))
    if report["summary"]:
        with (output / "summary.csv").open("w", newline="") as file:
            writer = csv.DictWriter(file, fieldnames=list(report["summary"][0]))
            writer.writeheader()
            writer.writerows(report["summary"])


def display_rows(summary):
    """Merge phases for display only; preserve per-phase measurements on disk."""
    grouped = {}
    for row in summary:
        grouped.setdefault(row["name"], {})[row["phase"]] = row
    rows = []
    for name, phases in grouped.items():
        first, cached = phases.get("first", {}), phases.get("cached", {})
        statuses = [phase.get("status", "missing") for phase in (first, cached)]
        row = {"name": name, "status": "ok" if statuses == ["ok", "ok"] else "/".join(statuses),
               "ok": statuses == ["ok", "ok"] and all(phase.get("visual_passed") is True for phase in (first, cached)),
               "wall_seconds": first.get("wall_seconds"),
               "cached_wall_seconds": cached.get("wall_seconds"),
               "render_seconds": first.get("render_seconds"), "render_fps": first.get("render_fps")}
        for field in ("cpu_percent", "tree_peak_mib", "device_gpu_utilization_percent"):
            values = [phase.get(field) if phase.get("status") == "ok" else None for phase in (first, cached)]
            row[field] = sum(values) / 2 if all(value is not None for value in values) else None
        rows.append(row)
    return rows


def print_results(report):
    table = Table(title="Render benchmark results", show_lines=False, padding=(0, 0))
    for column in ["Scene", "Wall s", "Cached wall s", "Render s", "FPS", "CPU %", "Tree MiB", "GPU %"]:
        table.add_column(column, justify="left" if column == "Scene" else "right", no_wrap=True)
    for row in display_rows(report["summary"]):
        numbers = [f"{row[field]:.2f}" if row[field] is not None else "—"
                   for field in ["wall_seconds", "cached_wall_seconds", "render_seconds"]]
        numbers += [f"{row[field]:.0f}" if row[field] is not None else "—"
                    for field in ["render_fps", "cpu_percent", "tree_peak_mib"]]
        utilization = row["device_gpu_utilization_percent"]
        color = "green" if row["ok"] else "red"
        table.add_row(f"[{color}]{row['name']}[/{color}]", *numbers,
                      f"{utilization:.0f}" if utilization is not None else "N/A")
    CONSOLE.print(table)
    CONSOLE.print("[dim]Wall/Render/FPS = first run; Cached wall = second run. CPU/GPU/memory = average of both runs; unavailable if either is missing.[/dim]")
    CONSOLE.print("[dim]GPU % is device-wide and includes other apps; N/A = unavailable. OS/driver caches are not reset.[/dim]")
    CONSOLE.print("[dim]CPU 100% = one logical core · Tree MiB = average of the two sampled process-tree RSS peaks[/dim]")
    passed = sum(r["status"] == "ok" for r in report["runs"])
    def duration(value):
        if value is None:
            return "not run"
        minutes, seconds = divmod(round(value), 60)
        return f"{minutes}m {seconds:02d}s"

    generation = report.get("video_generation_seconds", sum(r["wall_seconds"] for r in report["runs"]))
    validation = duration(report.get("validation_seconds"))
    if report.get("interrupted") and report.get("validation_seconds") is not None:
        validation += " (interrupted)"
    CONSOLE.print(f"\n[bold]{passed}/{len(report['runs'])} renders passed[/bold] · "
                  f"Video generation: {duration(generation)} · Validation: {validation}")
