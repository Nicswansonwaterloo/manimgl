"""Benchmark summaries, portable result files and revision comparisons."""
import csv
import hashlib
import importlib.metadata
import json
import platform
import statistics
import subprocess
import sys
from pathlib import Path

from rich.console import Console
from rich.table import Table

CONSOLE = Console()


def make_report(args, scenes, root, timestamp):
    """Record enough context to distinguish repository changes from workload changes."""
    def git(*arguments):
        try:
            return subprocess.check_output(["git", *arguments], cwd=root, text=True,
                                           stderr=subprocess.DEVNULL, timeout=5).strip()
        except (OSError, subprocess.SubprocessError):
            return None

    digest = hashlib.sha256()
    for scene in scenes:
        digest.update(scene["name"].encode())
        digest.update(Path(scene["file"]).read_bytes())
    for name in ["algorithms.py", "assets.py"]:
        digest.update((Path(__file__).parent / name).read_bytes())
    versions = {}
    for name in ["manimgl", "wgpu", "numpy", "av", "psutil"]:
        try:
            versions[name] = importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            versions[name] = None
    config_hash = hashlib.sha256()
    for path in [root / "manimlib/default_config.yml", root / "custom_config.yml"]:
        if path.exists():
            config_hash.update(path.read_bytes())
    return {
        "schema_version": 4, "created_at_utc": timestamp,
        "resolution": args.resolution, "fps": args.fps, "repeat": args.repeat,
        "gpu_timing_requested": args.gpu_timing,
        "encoding": {"codec": "libx264", "pixel_format": "yuv420p", "crf": 23},
        "scenes": scenes, "workload_sha256": digest.hexdigest(),
        "repository": {"commit": git("rev-parse", "HEAD"), "status": git("status", "--porcelain")},
        "environment": {"platform": platform.platform(), "python": sys.version, "packages": versions},
        "config_sha256": config_hash.hexdigest(), "runs": [], "interrupted": False,
    }


def comparison_rows(baseline, candidate):
    if baseline.get("schema_version") != 4 or candidate.get("schema_version") != 4:
        raise ValueError("Use results.json files generated by the current runner")
    for key in ["resolution", "fps", "gpu_timing_requested", "encoding", "workload_sha256"]:
        if baseline.get(key) != candidate.get(key):
            raise ValueError(f"Cannot compare: {key} differs; use the same scenes, settings and benchmark sources")
    if baseline.get("interrupted") or candidate.get("interrupted"):
        raise ValueError("Cannot compare interrupted runs; finish both suites first")
    expected = {scene["name"] for scene in baseline.get("scenes", baseline["summary"])}
    if any({row["name"] for row in report["summary"]} != expected for report in [baseline, candidate]):
        raise ValueError("Cannot compare incomplete suites; some selected scenes have no results")
    old = {row["name"]: row for row in baseline["summary"]}
    rows = []
    for current in candidate["summary"]:
        previous = old.get(current["name"])
        if previous is None:
            raise ValueError(f"Baseline has no result for {current['name']}")
        complete = (not previous["failed"] and not current["failed"]
                    and previous["passed"] == baseline.get("repeat", 1)
                    and current["passed"] == candidate.get("repeat", 1))
        def change(field):
            before, after = previous[field], current[field]
            return 100 * (after / before - 1) if complete and before and after is not None else None

        rows.append({"name": current["name"], "baseline_seconds": previous["render_seconds"],
                     "candidate_seconds": current["render_seconds"],
                     "render_change_percent": change("render_seconds"),
                     "wall_change_percent": change("wall_seconds")})
    return rows


def compare(baseline_path, candidate_path):
    def read(path):
        path = path / "results.json" if path.is_dir() else path
        return json.loads(path.read_text())

    baseline, candidate = read(baseline_path), read(candidate_path)
    rows = comparison_rows(baseline, candidate)
    for key in ["environment", "config_sha256"]:
        if baseline.get(key) != candidate.get(key):
            CONSOLE.print(f"[yellow]Review {key}: it differs between these runs.[/yellow]")
    old_adapters = {json.dumps(run.get("adapter"), sort_keys=True) for run in baseline["runs"]}
    new_adapters = {json.dumps(run.get("adapter"), sort_keys=True) for run in candidate["runs"]}
    if old_adapters != new_adapters:
        CONSOLE.print("[yellow]GPU adapter identity differs between these runs.[/yellow]")
    table = Table(title="Candidate vs baseline · median times", padding=(0, 0))
    for title in ["Scene", "Baseline s", "Candidate s", "Render Δ%", "Wall Δ%"]:
        table.add_column(title, justify="left" if title == "Scene" else "right")
    for row in rows:
        cells = [f"{row[key]:.2f}" if row[key] is not None else "—" for key in
                 ["baseline_seconds", "candidate_seconds", "render_change_percent", "wall_change_percent"]]
        table.add_row(row["name"], *cells)
    CONSOLE.print(table)
    CONSOLE.print("Negative = faster; positive = slower. Failed/incomplete scenes have no percentage.")


def summarize(runs):
    rows = []
    for name in dict.fromkeys(r["name"] for r in runs):
        all_runs = [r for r in runs if r["name"] == name]
        good = [r for r in all_runs if r["status"] == "ok"]
        row = {"name": name, "passed": len(good), "failed": len(all_runs) - len(good)}
        backends = sorted({r.get("adapter", {}).get("backend_type", "unknown")
                           for r in good if r.get("adapter")})
        row["backend"] = ", ".join(backends) or None
        row["gpu_confirmed"] = all(r.get("gpu_rendering", {}).get("hardware_rendering_confirmed", False)
                                   for r in good) if good else None
        for field in ["wall_seconds", "render_seconds", "render_fps", "cpu_percent", "tree_peak_mib", "worker_peak_mib",
                      "gpu_render_passes", "gpu_pass_mean_ms", "device_gpu_utilization_percent"]:
            values = [r[field] for r in good if r.get(field) is not None]
            row[field] = statistics.median(values) if values else None
        rows.append(row)
    return rows


def save_report(report, output):
    report["summary"] = summarize(report["runs"])
    (output / "results.json").write_text(json.dumps(report, indent=2))
    if report["summary"]:
        with (output / "summary.csv").open("w", newline="") as file:
            writer = csv.DictWriter(file, fieldnames=list(report["summary"][0]))
            writer.writeheader()
            writer.writerows(report["summary"])


def print_results(report):
    table = Table(title="Render benchmark results · medians of successful runs", show_lines=False, padding=(0, 0))
    for column in ["Scene", "P/F", "Wall s", "Render s", "FPS", "CPU %", "Tree MiB"]:
        table.add_column(column, justify="left" if column == "Scene" else "right", no_wrap=True)
    for row in sorted(report["summary"], key=lambda r: r["wall_seconds"] or 0, reverse=True):
        numbers = [f"{row[field]:.2f}" if row[field] is not None else "—"
                   for field in ["wall_seconds", "render_seconds", "render_fps", "cpu_percent", "tree_peak_mib"]]
        table.add_row(row["name"], f"{row['passed']}/{row['failed']}", *numbers,
                      style="red" if row["failed"] else None)
    CONSOLE.print(table)
    gpu_table = Table(title="GPU rendering evidence · medians of successful runs")
    for column in ["Scene", "Backend", "GPU", "Passes", "ms/pass", "Device %"]:
        gpu_table.add_column(column, justify="left" if column in {"Scene", "Backend"} else "right")
    for row in report["summary"]:
        gpu_passes = f"{row['gpu_render_passes']:g}" if row["gpu_render_passes"] is not None else "—"
        gpu_ms = f"{row['gpu_pass_mean_ms']:.3f}" if row["gpu_pass_mean_ms"] is not None else "—"
        confirmed = "yes" if row["gpu_confirmed"] else "unconfirmed" if row["passed"] else "—"
        utilization = row["device_gpu_utilization_percent"]
        gpu_table.add_row(row["name"], row["backend"] or "—", confirmed, gpu_passes, gpu_ms,
                          f"{utilization:.1f}" if utilization is not None else "—")
    CONSOLE.print(gpu_table)
    CONSOLE.print("[dim]Device % includes other apps; ms/pass measures GPU rendering only when valid timestamps are available.[/dim]")
    CONSOLE.print("[dim]CPU 100% = one logical core · Tree MiB = sampled peak process-tree RSS[/dim]")
    passed = sum(r["status"] == "ok" for r in report["runs"])
    CONSOLE.print(f"\n[bold]{passed}/{len(report['runs'])} renders passed[/bold] · "
                  f"total measured wall time: {sum(r['wall_seconds'] for r in report['runs']):.2f}s")
